// ---------------------------------------------------------------------------
// Pattern  –  one candidate schedule for a single machine
//
// A pattern is an ordered sequence of operations.  The machine processes
// them left-to-right without overlap.
// Consec(p) = { (seq[i], seq[i+1]) : i = 0 .. |seq|-2 }
// ---------------------------------------------------------------------------
struct Pattern {
    int              machine = -1;
    std::vector<Op>  seq;          ///< processing order
    std::set<Op>     op_set;       ///< set of operations covered
    std::vector<std::pair<Op,Op>> consec; ///< consecutive pairs
};

// ---------------------------------------------------------------------------
// Pattern generation
//
// Enumerates all permutations of all subsets of eligible operations for
// machine m, up to max_k operations per pattern.
// max_k < 0 means no cap.
// ---------------------------------------------------------------------------
static std::vector<Pattern> gen_patterns(int m, const Instance& inst, int max_k)
{
    // Collect operations that can be processed on machine m
    std::vector<Op> elig;
    for (int j = 0; j < inst.num_jobs; ++j)
        for (int o = 0; o < inst.num_ops[j]; ++o)
            if (inst.proc_time[j][o].count(m))
                elig.push_back({j, o});

    const int n   = static_cast<int>(elig.size());
    const int lim = (max_k < 0 || max_k > n) ? n : max_k;

    std::vector<Pattern> pats;

    // Empty pattern: machine m processes no operations in this candidate
    Pattern empty_pat;
    empty_pat.machine = m;
    pats.push_back(empty_pat);

    // For each subset size k = 1 .. lim
    for (int k = 1; k <= lim; ++k) {
        // Iterate over all C(n, k) index combinations
        std::vector<int> idx(k);
        std::iota(idx.begin(), idx.end(), 0);

        while (true) {
            // Build the k-element subset
            std::vector<Op> combo(k);
            for (int i = 0; i < k; ++i) combo[i] = elig[idx[i]];

            // Enumerate all k! orderings of this subset
            std::sort(combo.begin(), combo.end());
            do {
                Pattern p;
                p.machine = m;
                p.seq     = combo;
                p.op_set  = std::set<Op>(combo.begin(), combo.end());
                for (int i = 0; i + 1 < k; ++i)
                    p.consec.push_back({combo[i], combo[i + 1]});
                pats.push_back(std::move(p));
            } while (std::next_permutation(combo.begin(), combo.end()));

            // Advance to the next C(n, k) combination (Gosper's hack)
            int i = k - 1;
            while (i >= 0 && idx[i] == n - k + i) --i;
            if (i < 0) break;
            ++idx[i];
            for (int j2 = i + 1; j2 < k; ++j2) idx[j2] = idx[j2 - 1] + 1;
        }
    }

    return pats;
}

// ---------------------------------------------------------------------------
// Horizon  (loose upper bound on C_max; also serves as big-M)
// ---------------------------------------------------------------------------
static int compute_horizon(const Instance& inst)
{
    int h = 0;
    for (int j = 0; j < inst.num_jobs; ++j)
        for (int o = 0; o < inst.num_ops[j]; ++o)
            for (auto& [m2, pt] : inst.proc_time[j][o])
                h += pt;
    return h;
}

// ---------------------------------------------------------------------------
// Pretty-print schedule
// ---------------------------------------------------------------------------
static void print_schedule(const Schedule& sched, double makespan)
{
    std::cout << "\n=== Solution  Cmax = " << makespan << " ===\n";
    std::map<int, std::vector<std::tuple<int,int,int,int>>> by_mach;
    for (auto& [jop, mse] : sched) {
        auto [j, o]    = jop;
        auto [m2, sv, ev] = mse;
        by_mach[m2].emplace_back(j, o, sv, ev);
    }
    for (auto& [m2, ops] : by_mach) {
        std::sort(ops.begin(), ops.end(),
                  [](const auto& a, const auto& b) {
                      return std::get<2>(a) < std::get<2>(b);
                  });
        std::cout << "  M" << m2 << ":";
        for (auto& [j, o, sv, ev] : ops)
            std::cout << "  J" << j << "o" << o << "[" << sv << "," << ev << ")";
        std::cout << "\n";
    }
}

// ---------------------------------------------------------------------------
// Solve result
// ---------------------------------------------------------------------------
struct MILPResult {
    bool     found    = false;
    bool     optimal  = false;
    double   makespan = std::numeric_limits<double>::infinity();
    Schedule schedule;
};

// ---------------------------------------------------------------------------
// Build and solve the MILP
// ---------------------------------------------------------------------------
static MILPResult solve(const Instance& inst, double time_limit_sec, int max_k)
{
    MILPResult result;
    const int    J       = inst.num_jobs;
    const int    horizon = compute_horizon(inst);
    const double PI      = static_cast<double>(horizon);   // big-M

    // ----------------------------------------------------------------
    // 1.  Generate patterns for each machine
    // ----------------------------------------------------------------
    std::map<int, std::vector<Pattern>> pats;
    for (int m : inst.all_machines)
        pats[m] = gen_patterns(m, inst, max_k);

    // Guarantee coverage: for every operation, inject a singleton pattern
    // on each eligible machine if the operation is not yet covered.
    for (int j = 0; j < J; ++j) {
        for (int o = 0; o < inst.num_ops[j]; ++o) {
            Op op = {j, o};
            bool covered = false;
            for (int m : inst.elig_mach[j][o]) {
                for (auto& p : pats[m])
                    if (p.op_set.count(op)) { covered = true; break; }
                if (covered) break;
            }
            if (!covered) {
                for (int m : inst.elig_mach[j][o]) {
                    Pattern single;
                    single.machine = m;
                    single.seq     = {op};
                    single.op_set  = {op};
                    pats[m].push_back(std::move(single));
                }
            }
        }
    }

    // Report pattern counts
    std::size_t total_pats = 0;
    for (int m : inst.all_machines) {
        std::size_t cnt = pats[m].size();
        total_pats += cnt;
        std::cout << "  Machine " << std::setw(3) << m
                  << " : " << cnt << " patterns\n";
    }
    std::cout << "  Total patterns (binary vars): " << total_pats << "\n\n";

    // ----------------------------------------------------------------
    // 2.  Pre-index: op -> list of (machine, pattern_index) that cover it
    // ----------------------------------------------------------------
    std::map<Op, std::vector<std::pair<int,int>>> op_to_pats;
    for (int m : inst.all_machines)
        for (int pi = 0; pi < (int)pats[m].size(); ++pi)
            for (auto& op : pats[m][pi].op_set)
                op_to_pats[op].emplace_back(m, pi);

    // ----------------------------------------------------------------
    // 3.  CPLEX Concert Technology model
    // ----------------------------------------------------------------
    IloEnv   env;
    IloModel model(env);
    IloCplex cplex(model);

    // -- Decision variables --
    // y[m][pi] : binary – machine m selects pattern pi
    std::map<int, std::vector<IloBoolVar>> y;
    for (int m : inst.all_machines) {
        y[m].reserve(pats[m].size());
        for (int pi = 0; pi < (int)pats[m].size(); ++pi) {
            std::string nm = "y_m" + std::to_string(m)
                           + "_p" + std::to_string(pi);
            y[m].push_back(IloBoolVar(env, nm.c_str()));
        }
    }

    // s[j][o] : continuous start time of operation (j,o)
    std::map<Op, IloNumVar> s;
    for (int j = 0; j < J; ++j)
        for (int o = 0; o < inst.num_ops[j]; ++o) {
            std::string nm = "s_j" + std::to_string(j)
                           + "_o" + std::to_string(o);
            s[{j,o}] = IloNumVar(env, 0.0, PI, nm.c_str());
        }

    // cmax : makespan variable
    IloNumVar cmax(env, 0.0, PI, "cmax");

    // -- Objective: minimize C_max --
    model.add(IloMinimize(env, cmax));

    // ----------------------------------------------------------------
    // Constraint (1): each machine selects exactly one pattern
    //   sum_{p in P_m} y_{m,p} = 1    for all m in M
    // ----------------------------------------------------------------
    for (int m : inst.all_machines) {
        IloExpr expr(env);
        for (auto& yv : y[m]) expr += yv;
        model.add(IloRange(env, 1.0, expr, 1.0,
                           ("mach_cov_" + std::to_string(m)).c_str()));
        expr.end();
    }

    // ----------------------------------------------------------------
    // Constraint (2): each operation is covered by exactly one pattern
    //   sum_{m,p : (j,o) in p} y_{m,p} = 1    for all (j,o)
    // ----------------------------------------------------------------
    for (int j = 0; j < J; ++j) {
        for (int o = 0; o < inst.num_ops[j]; ++o) {
            Op op = {j, o};
            IloExpr expr(env);
            for (auto& [m2, pi] : op_to_pats[op])
                expr += y[m2][pi];
            model.add(IloRange(env, 1.0, expr, 1.0,
                               ("op_cov_j" + std::to_string(j)
                                + "_o" + std::to_string(o)).c_str()));
            expr.end();
        }
    }

    // ----------------------------------------------------------------
    // Constraint (3): consecutive ops in a selected pattern respect times
    //   s_u + p_{u,m} <= s_v + PI*(1 - y_{m,p})
    //   =>  s_u - s_v + PI * y_{m,p} <= PI - p_{u,m}
    //   for all m, p in P_m, (u,v) in Consec(p)
    // ----------------------------------------------------------------
    for (int m : inst.all_machines) {
        for (int pi = 0; pi < (int)pats[m].size(); ++pi) {
            for (auto& [u, v] : pats[m][pi].consec) {
                int pt_u = inst.proc_time[u.first][u.second].at(m);
                IloExpr expr(env);
                expr += s[u];
                expr -= s[v];
                expr += PI * y[m][pi];
                model.add(IloRange(env, -IloInfinity, expr,
                                   PI - static_cast<double>(pt_u)));
                expr.end();
            }
        }
    }

    // ----------------------------------------------------------------
    // Constraint (4): job-internal precedence (op o finishes before op o+1)
    //   s_{j,o} + sum_{m,p : (j,o) in p} p_{j,o,m} * y_{m,p} <= s_{j,o+1}
    //   for all j in J, o = 0 .. |O_j|-2
    // ----------------------------------------------------------------
    for (int j = 0; j < J; ++j) {
        for (int o = 0; o + 1 < inst.num_ops[j]; ++o) {
            Op op = {j, o};
            IloExpr expr(env);
            expr += s[op];
            for (auto& [m2, pi] : op_to_pats[op])
                expr += static_cast<double>(inst.proc_time[j][o].at(m2))
                        * y[m2][pi];
            expr -= s[{j, o + 1}];
            model.add(IloRange(env, -IloInfinity, expr, 0.0,
                               ("prec_j" + std::to_string(j)
                                + "_o" + std::to_string(o)).c_str()));
            expr.end();
        }
    }

    // ----------------------------------------------------------------
    // Constraint (5): last operation of each job bounds makespan
    //   s_{j,last} + sum_{m,p : (j,last) in p} p_{j,last,m} * y_{m,p} <= C_max
    //   for all j in J
    // ----------------------------------------------------------------
    for (int j = 0; j < J; ++j) {
        int last = inst.num_ops[j] - 1;
        Op  op   = {j, last};
        IloExpr expr(env);
        expr += s[op];
        for (auto& [m2, pi] : op_to_pats[op])
            expr += static_cast<double>(inst.proc_time[j][last].at(m2))
                    * y[m2][pi];
        expr -= cmax;
        model.add(IloRange(env, -IloInfinity, expr, 0.0,
                           ("mkspan_j" + std::to_string(j)).c_str()));
        expr.end();
    }

    // ----------------------------------------------------------------
    // Solver parameters
    // ----------------------------------------------------------------
    cplex.setParam(IloCplex::Param::MIP::Display, 2);
    if (time_limit_sec > 0.0)
        cplex.setParam(IloCplex::Param::TimeLimit, time_limit_sec);

    // ----------------------------------------------------------------
    // Incumbent callback: print Cmax + elapsed whenever a new integer
    // solution is found.
    // ----------------------------------------------------------------
    auto t0 = std::chrono::steady_clock::now();

    struct IncumbentPrinter : IloCplex::Callback::Function {
        std::chrono::steady_clock::time_point t0;
        explicit IncumbentPrinter(std::chrono::steady_clock::time_point t)
            : t0(t) {}
        void invoke(IloCplex::Callback::Context const& ctx) override {
            if (!ctx.inCandidate()) return;
            double obj     = ctx.getCandidateObjective();
            double elapsed = std::chrono::duration<double>(
                                 std::chrono::steady_clock::now() - t0).count();
            std::cout << "  [incumbent]  Cmax = " << std::fixed
                      << std::setprecision(2) << obj
                      << "   elapsed = " << elapsed << " s\n";
        }
    } printer(t0);
    cplex.use(&printer, IloCplex::Callback::Context::Id::Candidate);

    // ----------------------------------------------------------------
    // Solve
    // ----------------------------------------------------------------
    bool solved = false;
    try {
        solved = cplex.solve();
    } catch (IloException& ex) {
        std::cerr << "CPLEX exception: " << ex.getMessage() << "\n";
    }

    double elapsed =
        std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();

    auto status = cplex.getStatus();
    std::cout << "\nSolver status : ";
    switch (static_cast<int>(status)) {
        case static_cast<int>(IloAlgorithm::Optimal):   std::cout << "OPTIMAL\n";   break;
        case static_cast<int>(IloAlgorithm::Feasible):  std::cout << "FEASIBLE\n";  break;
        case static_cast<int>(IloAlgorithm::Infeasible):std::cout << "INFEASIBLE\n";break;
        default:                                         std::cout << "UNKNOWN\n";   break;
    }
    std::cout << "Wall time     : " << std::fixed << std::setprecision(2)
              << elapsed << " s\n";

    // ----------------------------------------------------------------
    // Extract solution
    // ----------------------------------------------------------------
    if (solved &&
        (status == IloAlgorithm::Optimal || status == IloAlgorithm::Feasible))
    {
        result.found    = true;
        result.optimal  = (status == IloAlgorithm::Optimal);
        result.makespan = cplex.getObjValue();

        for (int m : inst.all_machines) {
            for (int pi = 0; pi < (int)pats[m].size(); ++pi) {
                if (cplex.getValue(y[m][pi]) > 0.5) {
                    // Pattern pi is selected for machine m
                    for (auto& op : pats[m][pi].op_set) {
                        auto [j, o] = op;
                        int sv = static_cast<int>(
                                     std::round(cplex.getValue(s[op])));
                        int pt = inst.proc_time[j][o].at(m);
                        result.schedule[op] = {m, sv, sv + pt};
                    }
                }
            }
        }
    }

    env.end();
    return result;
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------
int main(int argc, char* argv[])
{
    InstanceName inst_name  = InstanceName::MEDIUM_7J7M;
    std::string  fjs_path;
    double       time_limit = 0.0;
    int          max_k      = -1;   // -1 = full enumeration (exact MILP)

    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        if      (arg == "--small"    || arg == "-s")    inst_name  = InstanceName::SMALL_6J6M;
        else if (arg == "--medium"   || arg == "-m")    inst_name  = InstanceName::MEDIUM_7J7M;
        else if (arg == "--large"    || arg == "-l")    inst_name  = InstanceName::LARGE_8J8M;
        else if (arg == "--xlarge"   || arg == "-xl")   inst_name  = InstanceName::XLARGE_9J9M;
        else if (arg == "--xxlarge"  || arg == "-xxl")  inst_name  = InstanceName::XLARGE_10J10M;
        else if (arg == "--xxxlarge" || arg == "-xxxl") inst_name  = InstanceName::XLARGE_11J11M;
        else if (arg == "--xxxlarge-vhf")                inst_name  = InstanceName::XLARGE_11J11M_VHF;
        else if (arg == "--xxxxlarge"|| arg == "-xxxxl")inst_name  = InstanceName::XLARGE_12J12M;
        else if ((arg == "--fjs") && i + 1 < argc)
            fjs_path = argv[++i];
        else if (arg == "--la03")                       inst_name  = InstanceName::LARGE_MACHINE_BASED_10J5M;
        else if ((arg == "--time" || arg == "-t") && i + 1 < argc)
            time_limit = std::stod(argv[++i]);
        else if (arg == "--help" || arg == "-h") {
            std::cout <<
                "Usage: milp [--small|--medium|--large|--xlarge|"
                "--xxlarge|--xxxlarge|--xxxlarge-vhf|--xxxxlarge|--la03]\n"
                "            [--fjs <path.fjs>]\n"
                "            [--time <seconds>]\n"
                "\n"
                "Instance flags (default: --medium):\n"
                "  --small      :  6 jobs,  6 machines\n"
                "  --medium     :  7 jobs,  7 machines\n"
                "  --large      :  8 jobs,  8 machines\n"
                "  --xlarge     :  9 jobs,  9 machines\n"
                "  --xxlarge    : 10 jobs, 10 machines\n"
                "  --xxxlarge   : 11 jobs, 11 machines\n"
                "  --xxxlarge-vhf : 11 jobs, 11 machines (very high flex hard)\n"
                "  --xxxxlarge  : 12 jobs, 12 machines (very high flex)\n"
                "  --la03       : LA03, 10 jobs, 5 machines\n"
                "  --fjs <path> : external FJSSP benchmark file\n"
                "\n"
                "Options:\n"
                "  --time <s>   : CPLEX wall-clock time limit in seconds\n";
            return 0;
        }
    }

    Instance inst = get_instance(inst_name);
                                    //  : load_fjs_instance(fjs_path);

    int total_ops = 0;
    for (int j = 0; j < inst.num_jobs; ++j) total_ops += inst.num_ops[j];

    std::cout << "=== FJSSP Pattern-based MILP Solver ===\n";
    std::cout << "  Instance   : " << inst.name           << "\n";
    std::cout << "  Jobs       : " << inst.num_jobs        << "\n";
    std::cout << "  Machines   : " << inst.num_machines    << "\n";
    std::cout << "  Total ops  : " << total_ops            << "\n";
    std::cout << "  Horizon    : " << compute_horizon(inst) << "\n";
    std::cout << "  Patterns   : full P_m (all ordered subsets)\n";
    if (time_limit > 0.0)
        std::cout << "  Time limit : " << time_limit << " s\n";
    std::cout << "\nGenerating patterns ...\n";

    MILPResult res = solve(inst, time_limit, max_k);

    if (res.found) {
        print_schedule(res.schedule, res.makespan);
        std::cout << "\nMakespan: " << res.makespan
                  << (res.optimal ? "  (OPTIMAL)" : "  (FEASIBLE)") << "\n";
    } else {
        std::cout << "\nNo solution found.\n";
    }

    return 0;
}
