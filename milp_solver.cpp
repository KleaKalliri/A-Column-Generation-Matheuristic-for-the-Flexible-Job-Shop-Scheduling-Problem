// =============================================================================
// milp_solver.cpp  –  Pattern-based MILP for FJSSP  (CPLEX Concert Technology)
//
// Implements the formulation:
//
//   min  C_max
//
//   s.t.
//   (1)  sum_{p in P_m} y_{m,p} = 1
//            for all m in M
//
//   (2)  sum_{m in M, p in P_m : (j,o) in p} y_{m,p} = 1
//            for all j in J, o in O_j
//
//   (3)  s_u + p_{u,m} <= s_v + PI*(1 - y_{m,p})
//            for all m in M, p in P_m, (u,v) in Consec(p)
//
//   (4)  s_{j,o} + sum_{m in M, p in P_m} p_{j,o,m} * a_{j,o,m,p} * y_{m,p}
//            <= s_{j,o+1}
//            for all j in J, o = 1, ..., |O_j| - 1
//
//   (5)  s_{j,last} + sum_{m in M, p in P_m} p_{j,last,m} * a_{j,last,m,p} * y_{m,p}
//            <= C_max
//            for all j in J
//
//   y_{m,p} in {0,1},  s_{j,o} >= 0,  C_max >= 0
//
// Notation:
//   P_m             : set of patterns (ordered schedules) for machine m
//   p_{u,m}         : processing time of op u on machine m
//   a_{j,o,m,p} = 1 : iff operation (j,o) is covered by pattern p on machine m
//   Consec(p)       : consecutive op-pairs in pattern p  (ordered by processing seq)
//   PI              : big-M (= sum of all processing times, i.e. the horizon)
//
// Patterns are generated by enumerating ALL ordered subsets of eligible
// operations for each machine (the full set P_m), giving the exact MILP.
//
// Usage:
//   milp [--small | --medium | --large | --xlarge | --xxlarge |
//         --xxxlarge | --xxxxlarge | --la03]
//        [--time <seconds>]
// =============================================================================

